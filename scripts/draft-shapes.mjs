const k = (p) => p[0] + ',' + p[1];
const same = (a, b) => a[0] === b[0] && a[1] === b[1];

// 경계선 name에서 꼭짓점 a부터 b까지 (방향은 a→b)
function seg(name, a, b) {
  const line = L[name];
  if (!line) throw new Error('no line ' + name);
  const i = line.findIndex((p) => same(p, a));
  const j = line.findIndex((p) => same(p, b));
  if (i < 0 || j < 0) throw new Error(`${name}: 꼭짓점 없음 ${a} / ${b}`);
  return i <= j ? line.slice(i, j + 1) : line.slice(j, i + 1).reverse();
}
const all = (name) => L[name].slice();
const rev = (name) => L[name].slice().reverse();

// 조각들을 이어 닫힌 고리로 만든다
function ring(...parts) {
  const out = [];
  for (const part of parts) {
    const pts = typeof part[0] === 'number' ? [part] : part;
    for (const p of pts) if (!out.length || !same(out[out.length - 1], p)) out.push(p);
  }
  if (same(out[0], out[out.length - 1])) out.pop();
  // 연결 확인: 한 꼭짓점이 두 번 나오면 고리가 꼬인 것
  const seen = new Set();
  for (const p of out) { if (seen.has(k(p))) throw new Error('꼭짓점 중복 ' + k(p)); seen.add(k(p)); }
  out.push(out[0]);
  if (area(out) < 0) out.reverse(); // RFC 7946: 바깥 고리는 반시계 방향
  return out;
}
function area(r) { let a = 0; for (let i = 0; i < r.length - 1; i++) a += r[i][0] * r[i + 1][1] - r[i + 1][0] * r[i][1]; return a / 2; }

// 꼭짓점을 공유하는 고리들을 하나로 합친다 (공유 변을 지운다)
function union(...rings) {
  const edges = new Map();
  for (const r of rings) for (let i = 0; i < r.length - 1; i++) {
    const a = k(r[i]), b = k(r[i + 1]);
    if (edges.has(b + '>' + a)) edges.delete(b + '>' + a); else edges.set(a + '>' + b, [r[i], r[i + 1]]);
  }
  const next = new Map();
  for (const [, [a, b]] of edges) { if (next.has(k(a))) throw new Error('union: 분기점 ' + k(a)); next.set(k(a), b); }
  const out = [];
  const used = new Set();
  for (const [, [a]] of edges) {
    if (used.has(k(a))) continue;
    const r = [a]; used.add(k(a));
    let cur = next.get(k(a));
    while (!same(cur, a)) { r.push(cur); used.add(k(cur)); cur = next.get(k(cur)); }
    r.push(a);
    out.push(r);
  }
  if (out.length !== 1) throw new Error('union 결과 고리 ' + out.length + '개');
  return out[0];
}

function circle([x, y], rx, n = 10) {
  const ry = rx * 0.8;
  const r = [];
  for (let i = 0; i < n; i++) { const t = (i / n) * 2 * Math.PI; r.push([+(x + rx * Math.cos(t)).toFixed(4), +(y + ry * Math.sin(t)).toFixed(4)]); }
  return ring(r);
}

