function centroid(r) {
  let a = 0, cx = 0, cy = 0;
  for (let i = 0; i < r.length - 1; i++) {
    const f = r[i][0] * r[i + 1][1] - r[i + 1][0] * r[i][1];
    a += f; cx += (r[i][0] + r[i + 1][0]) * f; cy += (r[i][1] + r[i + 1][1]) * f;
  }
  return [+(cx / (3 * a)).toFixed(2), +(cy / (3 * a)).toFixed(2)];
}
function F(rings, p) {
  const rs = Array.isArray(rings[0][0]) ? rings : [rings];
  const geometry = rs.length === 1 ? { type: 'Polygon', coordinates: [rs[0]] } : { type: 'MultiPolygon', coordinates: rs.map((r) => [r]) };
  const props = {
    name: p.name, start: p.start, end: p.end,
    role: p.role || 'korea', confidence: p.c || '대략', basis: p.basis,
    anchor: p.anchor || centroid(rs[0]),
  };
  if (p.startMonth) props.startMonth = p.startMonth;
  if (p.endMonth) props.endMonth = p.endMonth;
  if (p.fillAs) props.fillAs = p.fillAs;
  return { type: 'Feature', properties: props, geometry };
}
